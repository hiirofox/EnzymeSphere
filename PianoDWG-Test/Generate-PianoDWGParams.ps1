[CmdletBinding()]
param(
    [string]$TasksDirectory = (Join-Path $PSScriptRoot '../test/tasks'),
    [string]$OutputPath = (Join-Path $PSScriptRoot 'PianoDWGParams.h')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$prefix = 'checkpoint-dwg2-'
$firstNote = 21
$lastNote = 108
$numParams = 6303 # PianoDWG::PianoWaveguide2<float>::NumParams
$culture = [Globalization.CultureInfo]::InvariantCulture
$numberStyle = [Globalization.NumberStyles]::Float
$rows = @{}

foreach ($file in Get-ChildItem -LiteralPath $TasksDirectory -File -Filter "$prefix*.txt") {
    if ($file.BaseName -cnotmatch '^checkpoint-dwg2-(\d{3})[A-G](?:b|#)?$') {
        throw "Invalid checkpoint filename: $($file.Name)"
    }
    $note = [int]$Matches[1]
    if ($note -lt $firstNote -or $note -gt $lastNote -or $rows.ContainsKey($note)) {
        throw "Out-of-range or duplicate MIDI note in $($file.Name)"
    }

    $content = [IO.File]::ReadAllText($file.FullName).Trim().TrimEnd(',').TrimEnd()
    $tokens = $content -split '\s*,\s*'
    if ($tokens.Count -ne $numParams) {
        throw "$($file.Name) has $($tokens.Count) parameters. Expected $numParams."
    }

    $literals = [string[]]::new($numParams)
    for ($i = 0; $i -lt $numParams; ++$i) {
        $token = $tokens[$i]
        $value = [single]0
        if ($token -cnotmatch '^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?$' -or
            -not [single]::TryParse($token, $numberStyle, $culture, [ref]$value) -or
            [single]::IsNaN($value) -or [single]::IsInfinity($value)) {
            throw "$($file.Name) contains an invalid float at parameter $($i + 1): $token"
        }
        if ($token -notmatch '[.eE]') { $token += '.0' }
        $literals[$i] = $token + 'f'
    }
    $rows.Add($note, @{ Name = $file.BaseName; Literals = $literals })
}

if ($rows.Count -eq 0) { throw "No $prefix*.txt files found in $TasksDirectory" }
$notes = @($rows.Keys | Sort-Object)

$lines = [Collections.Generic.List[string]]::new()
$lines.AddRange([string[]]@(
    '#pragma once',
    '',
    '// Generated by Generate-PianoDWGParams.ps1. Each Params row corresponds to MidiNotes.',
    'namespace PianoDWGParams_Piano1 {',
    "inline constexpr int FirstNote = $firstNote, LastNote = $lastNote;",
    "inline constexpr int NumNotes = $($notes.Count), NumParams = $numParams;",
    'inline constexpr int MidiNotes[NumNotes] = {',
    ('    ' + ($notes -join ', ')),
    '};',
    '',
    'inline constexpr int RowForNote(int note) noexcept {',
    '    for (int row = 0; row < NumNotes; ++row)',
    '        if (MidiNotes[row] == note) return row;',
    '    return -1;',
    '}',
    '',
    'inline constexpr float Params[NumNotes][NumParams] = {'
))
foreach ($note in $notes) {
    $row = $rows[$note]
    $lines.Add(('    {{ // {0}' -f $row.Name))
    for ($i = 0; $i -lt $numParams; $i += 12) {
        $last = [Math]::Min($i + 11, $numParams - 1)
        $lines.Add('        ' + ($row.Literals[$i..$last] -join ', ') + ',')
    }
    $lines.Add('    },')
}
$lines.Add('};')
$lines.Add('} // namespace PianoDWGParams_Piano1')

$output = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputPath)
[IO.File]::WriteAllLines($output, $lines, [Text.UTF8Encoding]::new($false))
Write-Output "Generated $($notes.Count) rows x $numParams parameters in $output"
